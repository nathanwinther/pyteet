class Migrate(Command):

    NAME = 'migrate'
    DESC = 'Database migration commands'
    LONG_DESC = '''Database migration commands

Commands

apply                      Apply migrations
rollback --batch [batchid] Rollback batch
status                     View migrations status
'''

    def __call__(self, args: list | None=[]):
        parser = argparse.ArgumentParser(
                description=self.LONG_DESC,
                exit_on_error=False,
                formatter_class=argparse.RawTextHelpFormatter,
                usage=self.NAME)
        parser.add_argument(
                'command',
                help='command',
                type=str)
        parser.add_argument(
                '-b',
                '--batch',
                default=None,
                help='batch id for rollback',
                type=int)
        try:
            parsed = parser.parse_args(args)
            if hasattr(self, parsed.command):
                if parsed.command == 'rollback':
                    getattr(self, parsed.command)(parsed.batch)
                else:
                    getattr(self, parsed.command)()
            else:
                parser.print_help()
        except argparse.ArgumentError:
            parser.print_help()

    def apply(self):
        state = _get_migrations()
        unprocessed = [item for item in state if item['processed'] == False]
        if not unprocessed:
            return
        db = database()
        dt = datetime.now(UTC).strftime(DATETIME)
        def _max_batch(acc, item):
            batch = parseint(item.get('batch', ''))
            return batch if batch > acc else acc
        max_batch = reduce(_max_batch, state, 0)
        for item in unprocessed:
            migration = item['migration']
            print(f'{migration} migration started')
            module = importlib.import_module(item['module'])
            getattr(module, 'migrate')()
            sql = '''
                INSERT INTO pyteet_migrations
                (migration, batch, created_at, updated_at)
                VALUES(%s, %s, %s, %s)
            '''
            db.execute(sql, (migration, max_batch + 1, dt, dt))
            print(f'{migration} migration complete')

    def rollback(self, batch: int):
        state = _get_migrations()
        if not batch:
            def _max_batch(acc, item):
                batch = parseint(item.get('batch', ''))
                return batch if batch > acc else acc
            batch = reduce(_max_batch, state, 0)
        if not batch:
            return
        db = database()
        sql = '''
            SELECT
            *
            FROM pyteet_migrations
            WHERE batch = %s
        '''
        rows = db.fetchall(sql, (batch, ))
        for row in rows:
            migration = row['migration']
            print(f'{migration} rollback started')
            module = importlib.import_module(f'migrations.{migration}')
            getattr(module, 'rollback')()
            print(f'{migration} rollback complete')
        sql = '''
            DELETE FROM pyteet_migrations
            WHERE batch = %s
        '''
        db.execute(sql, (batch, ))

    def status(self):
        def print_sep(max_len):
            print('{}{}{}{}{}{}{}'.format(
                '+-',
                '-' * max_len[0],
                '-+-',
                '-' * max_len[1],
                '-+-',
                '-' * max_len[2],
                '-+'))
        def print_row(row, max_len):
            print('{}{}{}{}{}{}{}'.format(
                '| ',
                row[0].ljust(max_len[0]),
                ' | ',
                row[1].ljust(max_len[1]),
                ' | ',
                row[2].ljust(max_len[2]),
                ' |'))
        state = _get_migrations()
        header = ['Ran?', 'Migration', 'Batch']
        max_len = [len(x) for x in header]
        for k, v in enumerate(state):
            len_mgrtn = len(v['migration'])
            max_len[1] = len_mgrtn if len_mgrtn > max_len[1] else max_len[1]
            len_batch = len(str(v['batch']))
            max_len[2] = len_batch if len_batch > max_len[2] else max_len[2]
            state[k] = [
                    'Yes' if v['processed'] else 'No',
                    v['migration'],
                    str(v['batch']),
                    ]
        print_sep(max_len)
        print_row(header, max_len)
        print_sep(max_len)
        if state:
            for row in state:
                print_row(row, max_len)
            print_sep(max_len)

class PAT(Command):

    NAME = 'pat'
    DESC = 'Install PAT migration'

    def __call__(self, args: list | None=[]):
        parser = argparse.ArgumentParser(
                description=self.DESC,
                usage=self.NAME)
        parser.add_argument(
                '-i',
                '--install',
                action='store_true',
                help='install')
        parsed = parser.parse_args(args)
        if parsed.install:
            prefix = datetime.now(UTC).strftime('%Y%m%d%H%M%S')
            suffix = '_create_pyteet_pat'

            state = _get_migrations()
            for item in state:
                if item['migration'].endswith(suffix):
                    print('PAT migration already installed')
                    return

            tpl_root = Path(__file__).resolve().parent / 'templates'
            proj_root = Path().cwd()

            db = database()
            if db.driver == 'mysql':
                with open(tpl_root / 'pat_mysql.py', 'r') as r:
                    contents = r.read()
            elif db.driver == 'postgres':
                with open(tpl_root / 'pat_postgres.py', 'r') as r:
                    contents = r.read()
            elif db.driver == 'sqlite':
                with open(tpl_root / 'pat_sqlite.py', 'r') as r:
                    contents = r.read()
            else:
                raise ValueError(f'{db.driver} driver not supported.')

            migrations = proj_root / 'migrations'
            if not migrations.exists():
                migrations.mkdir()

            path = migrations / f'{prefix}{suffix}.py'
            with open(path.as_posix(), 'w') as w:
                w.write(contents.format(name=f'{prefix}{suffix}'))

            print(f'created: {path.as_posix()}')
        else:
            parser.print_help()


def get_commands() -> dict:
    def validate(inst):
        must_have = ('NAME', 'DESC', '__call__')
        for k in must_have:
            if not hasattr(inst, k):
                return False
        return True

    commands = {
            Env.NAME: Env(),
            Init.NAME: Init(),
            Make.NAME: Make(),
            Migrate.NAME: Migrate(),
            PAT.NAME: PAT(),
            }

    # Get app command path
    path = Path().cwd() / 'commands'
    if not path.exists():
        return commands

    for file in path.iterdir():
        if not file.is_file():
            continue
        if file.suffix != '.py':
            continue

        module_name = f'commands.{file.stem}'
        module = importlib.import_module(module_name)

        try:
            cls_name = _snake_to_camel(file.stem)
            inst = getattr(module, cls_name)()
            if isinstance(inst, Command):
                if validate(inst):
                    commands[inst.NAME] = inst
        except Exception as e:
            logger.error(e)
            logger.exception(e)

    return commands

def _camel_to_snake(value: str) -> str:
    value = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', value)
    value = re.sub(r'([a-z\d])([A-Z])', r'\1_\2', value)
    return value.lower()

def _get_migrations():
    def find(state, migration):
        for idx, item in enumerate(state):
            if item['migration'] == migration:
                return idx
        return -1

    def validate(module):
        must_have = ('NAME', 'migrate', 'rollback')
        for k in must_have:
            if not hasattr(module, k):
                return False
        return True

    # Get migrations
    state = []
    db = database()

    try:
        sql = '''
            SELECT
            *
            FROM pyteet_migrations
        '''
        state = db.fetchall(sql)
    except:
        logger.debug(f'pyteet_migrations does not exist, create.')
        if db.driver == 'mysql':
            sql = '''
                CREATE TABLE pyteet_migrations (
                    id bigint unsigned NOT NULL AUTO_INCREMENT,
                    migration varchar(255) NOT NULL,
                    batch bigint unsigned NOT NULL,
                    created_at timestamp NULL DEFAULT NULL,
                    updated_at timestamp NULL DEFAULT NULL,
                    PRIMARY KEY (id)
                )
            '''
        if db.driver == 'postgres':
            sql = '''
                CREATE TABLE pyteet_migrations (
                    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                    migration varchar(255) NOT NULL,
                    batch bigint NOT NULL,
                    created_at timestamp NULL DEFAULT NULL,
                    updated_at timestamp NULL DEFAULT NULL
                )
            '''
        if db.driver == 'sqlite':
            sql = '''
                CREATE TABLE pyteet_migrations (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    migration TEXT NOT NULL,
                    batch INTEGER NOT NULL,
                    created_at TEXT NULL,
                    updated_at TEXT NULL
                )
            '''
        db.execute(sql)

    # Find migrations
    path = Path().cwd() / 'migrations'
    if path.exists():
        for file in path.iterdir():
            if not file.is_file():
                continue
            if file.suffix != '.py':
                continue
            module_name = f'migrations.{file.stem}'
            module = importlib.import_module(module_name)
            if not validate(module):
                continue
            migration = getattr(module, 'NAME')
            idx = find(state, migration)
            if idx >= 0:
                state[idx]['processed'] = True
            else:
                state.append({
                    'id': '',
                    'migration': migration,
                    'batch': '',
                    'processed': False,
                    'module': module_name,
                    })

    # Filter out states with UNKNOWN processed state
    state = [x for x in state if 'processed' in x]

    # Sort
    state = sorted(state, key=itemgetter('migration'))
    return state

def _pluralize(word: str) -> str:
    # Simle pluralize
    # https://www.geeksforgeeks.org/python/python-program-to-convert-singular-to-plural/
    # Check if word is ending with s,x,z or is
    # ending with ah, eh, ih, oh,uh,dh,gh,kh,ph,rh,sh,th
    word = str(word).strip()
    if re.search(r'[sxz]$', word) or re.search(r'[aeioudgkprst]h$', word):
        # Make it plural by adding es in end
        return word + 'es'
    # Check if word is ending with y
    elif re.search(r'y$', word):
        # Make it plural by removing y from end adding ies to end
        return re.sub(r'y$', 'ies', word)
    # In all the other cases
    else:
        # Make the plural of word by adding s in end
        return word + 's'

def _snake_to_camel(value: str) -> str:
    segments = value.split('_')
    segments = [x.capitalize() for x in segments]
    return ''.join(segments)

